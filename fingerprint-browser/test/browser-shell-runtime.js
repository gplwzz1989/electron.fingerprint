// 使用现有 Electron 运行时执行隔离验收；不读取正式账户，不访问外部网站。
const { app, BrowserWindow, WebContentsView, ipcMain } = require('electron/main')
const fs = require('node:fs')
const os = require('node:os')
const path = require('node:path')
const http = require('node:http')
const assert = require('node:assert/strict')
const { pathToFileURL } = require('node:url')
const clientRoot = process.env.FP_SHELL_TEST_APP_DIR || path.resolve(__dirname, '..')
const { TabBrowser } = require(path.join(clientRoot, 'browser-tabs'))
const { TabCapabilities } = require(path.join(clientRoot, 'tab-capabilities'))
const { bridgeArguments } = require(path.join(clientRoot, 'client-api-contract'))
const { EnvironmentRepository } = require(path.join(clientRoot, 'environment-repository'))
const { AutomationServer } = require(path.join(clientRoot, 'automation-server'))
const { createProfileRecord, getDefaultProfile } = require(path.join(clientRoot, 'profile-store'))
const directory = fs.mkdtempSync(path.join(os.tmpdir(), 'qijie-real-shell-'))
const reportPath = process.argv[2]
app.setPath('userData', directory)
app.setPath('sessionData', directory)
const results = []
let window; let controller; let automation; const servers = []
const timer = setTimeout(() => { fs.writeFileSync(reportPath, JSON.stringify({ ok: false, message: '运行时验收超时。', results })); app.exit(1) }, 60000)
function record (name) { results.push(name) }
async function listen () {
  // 子框架使用独立的空文档，避免无穷加载影响真实页面验收。
  const server = http.createServer((req, res) => { res.setHeader('Content-Type', 'text/html; charset=utf-8'); res.end(req.url === '/frame' ? '<!doctype html><title>子框架验收</title>' : '<!doctype html><html lang="zh-CN"><title>隔离网页验收</title><body>本机真实网页<iframe src="/frame" title="隔离子框架"></iframe></body></html>') })
  await new Promise(resolve => server.listen(0, '127.0.0.1', resolve)); servers.push(server)
  return `http://127.0.0.1:${server.address().port}`
}
app.whenReady().then(async () => {
  const origin = await listen(); const other = await listen(); const homeUrl = origin + '/'
  const registry = new TabCapabilities()
  const repository = new EnvironmentRepository(directory); await repository.load()
  automation = new AutomationServer({ port: 0, environmentRepository: repository }); await automation.start()
  window = new BrowserWindow({ width: 1180, height: 820, show: false, frame: false, webPreferences: { preload: path.join(clientRoot, 'browser-shell-preload.js'), contextIsolation: true, nodeIntegration: false, sandbox: true } })
  window.webContents.setBackgroundThrottling(false)
  controller = new TabBrowser(directory, repository, { getWindow: () => window, capabilityRegistry: registry, onSessionCreated: value => automation.attachSession(value, registry) })
  controller.attachWindow(window)
  const home = new WebContentsView({ webPreferences: { preload: path.join(clientRoot, 'desktop-preload.js'), additionalArguments: bridgeArguments(), contextIsolation: true, nodeIntegration: false, sandbox: true } })
  registry.register(home.webContents, 'home', { pinnedUrl: homeUrl }); automation.attachSession(home.webContents.session, registry)
  controller.attachDashboard(home, homeUrl)
  const shellUrl = pathToFileURL(path.join(clientRoot, 'browser-shell.html')).href
  registry.register(window.webContents, 'shell', { pinnedUrl: shellUrl })
  const handle = (channel, callback) => ipcMain.handle(channel, async (event, payload) => { try { registry.assert(event, channel); return await callback(payload) } catch { return { ok: false } } })
  handle('application:runtime', () => ({ ok: true, platform: process.platform, chromiumVersion: process.versions.chrome }))
  handle('tabs:list', () => ({ ok: true, ...controller.snapshot() }))
  handle('tabs:ordinary', async () => ({ ok: true, ...await controller.openOrdinary() }))
  handle('tabs:select', id => { controller.select(id); return { ok: true } })
  handle('tabs:close', async id => { await controller.close(id); return { ok: true } })
  handle('tabs:reorder', payload => ({ ok: true, ...controller.reorder(payload) }))
  handle('tabs:dashboard', () => { controller.selectDashboard(); return { ok: true } })
  handle('tabs:navigate', async value => { await controller.navigate(value); return { ok: true } })
  await window.loadURL(shellUrl); await home.webContents.loadURL(homeUrl)
  assert.equal((await home.webContents.executeJavaScript('window.desktopBridge.runtime()')).ok, true)
  assert.equal(await home.webContents.executeJavaScript('typeof window.browserApi.saveProfile'), 'function')
  assert.equal(await window.webContents.executeJavaScript('typeof window.browserApi'), 'undefined')
  assert.equal(home.getBounds().y, 94); record('固定首页完整业务桥接，外壳只暴露控制能力，内容区域正确避开顶部 94 像素')
  const apiUrl = `http://127.0.0.1:${automation.port}/api/v1/health`
  assert.equal(await home.webContents.executeJavaScript(`fetch(${JSON.stringify(apiUrl)}).then(r=>r.status)`), 200)
  record('固定 SaaS 标签访问 HTTP API 自动免填令牌')
  const ordinaryResult = await controller.openOrdinary(homeUrl); const ordinary = controller.getTab(ordinaryResult.tabId).view.webContents
  assert.deepEqual(await ordinary.executeJavaScript('[typeof desktopBridge, typeof browserApi, typeof require]'), ['undefined', 'undefined', 'undefined'])
  assert.equal(await ordinary.executeJavaScript(`fetch(${JSON.stringify(apiUrl)}).then(r=>r.status)`), 403)
  assert.equal(await ordinary.executeJavaScript(`fetch(${JSON.stringify(apiUrl)}, {headers:{Authorization:${JSON.stringify('Bearer ' + automation.token)}}}).then(r=>r.status)`), 200)
  record('普通标签即使打开相同 SaaS 地址也无原生桥接；HTTP 无令牌拒绝，有令牌允许')
  const managedResult = await controller.createManaged({ url: homeUrl }); const managed = controller.getTab(managedResult.tabId).view.webContents
  assert.equal((await managed.executeJavaScript('window.desktopBridge.runtime()')).ok, true)
  assert.equal(await managed.executeJavaScript(`fetch(${JSON.stringify(apiUrl)}).then(r=>r.status)`), 200)
  controller.setCapabilities({ id: managedResult.tabId, capabilities: [] })
  assert.equal((await managed.executeJavaScript('window.desktopBridge.runtime()')).ok, false)
  assert.equal(await managed.executeJavaScript(`fetch(${JSON.stringify(apiUrl)}).then(r=>r.status)`), 403)
  controller.setCapabilities({ id: managedResult.tabId, capabilities: ['application', 'automation'] })
  assert.equal((await managed.executeJavaScript('window.desktopBridge.runtime()')).ok, true)
  await controller.navigate({ id: managedResult.tabId, action: 'load', url: other + '/' })
  assert.equal((await managed.executeJavaScript('window.desktopBridge.runtime()')).ok, false)
  controller.setCapabilities({ id: managedResult.tabId, allowedOrigins: [other] })
  assert.equal((await managed.executeJavaScript('window.desktopBridge.runtime()')).ok, true)
  record('系统创建标签支持完整或部分能力、即时撤销、跨站重新校验和显式授权')
  const frame = managed.mainFrame.frames[0]
  assert.equal(await frame.executeJavaScript('typeof desktopBridge'), 'undefined')
  await controller.close(managedResult.tabId); assert.equal(registry.entries.has(managed.id), false)
  record('子框架没有独立桥接；关闭标签撤销身份和授权')
  const profile = createProfileRecord({ id: 'isolated-runtime-environment', name: '隔离运行时环境', url: homeUrl, fingerprint: getDefaultProfile() })
  const environment = await repository.create(profile, homeUrl)
  const environmentResult = await controller.createManaged({ environmentId: environment.id, url: homeUrl, capabilities: ['application', 'automation'] })
  const environmentTab = controller.getTab(environmentResult.tabId)
  assert.equal((await environmentTab.view.webContents.executeJavaScript('desktopBridge.runtime()')).ok, true)
  assert.equal(await environmentTab.view.webContents.executeJavaScript(`fetch(${JSON.stringify(apiUrl)}).then(r=>r.status)`), 200)
  await environmentTab.view.webContents.session.cookies.set({ url: homeUrl, name: 'runtime-session-check', value: 'isolated-value' })
  assert.equal((await ordinary.session.cookies.get({ url: homeUrl, name: 'runtime-session-check' })).length, 0)
  const popup = await controller.openOrdinary(homeUrl, { session: environmentTab.view.webContents.session, ownerEnvironmentId: environment.id })
  assert.equal(await controller.getTab(popup.tabId).view.webContents.executeJavaScript('typeof desktopBridge'), 'undefined')
  await controller.closeEnvironment(environment.id)
  assert(!controller.tabs.has(popup.tabId)); assert(controller.tabs.has(ordinaryResult.tabId))
  record('真实指纹环境标签保留沙箱防检测预加载与业务桥接，Cookie 与普通浏览器会话隔离')
  await assert.rejects(() => controller.navigate({ id: null, action: 'load', url: other + '/' }))
  controller.selectDashboard(); assert.equal(home.webContents.getURL(), homeUrl)
  window.setSize(1440, 900); controller.layout(); assert.equal(home.getBounds().height, window.getContentSize()[1] - 94)
  const blankResult = await controller.openOrdinary(); const blank = controller.getTab(blankResult.tabId).view.webContents
  assert.equal(controller.snapshot().tabs.find(tab => tab.id === blankResult.tabId).url, 'about:blank')
  assert.equal(await blank.executeJavaScript('document.querySelector("input").placeholder'), '搜索或输入网址')
  await controller.navigate({ id: blankResult.tabId, action: 'load', url: origin.replace('http://', '') + '/one' })
  assert.equal(blank.getURL(), origin + '/one')
  await controller.navigate({ id: blankResult.tabId, action: 'load', url: origin + '/two' })
  assert(blank.navigationHistory.canGoBack())
  record('固定首页不可替换；普通新标签不要求环境；真实网址加载和历史导航可用；窗口尺寸变化正确更新布局')
  for (let i = 0; i < 8; i++) await controller.openOrdinary()
  await window.webContents.executeJavaScript('new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(() => resolve(true))))')
  const overflow = await window.webContents.executeJavaScript(`(function(){const list=document.querySelector('.browser-tabs');const active=list.querySelector('.active');const bounds=list.getBoundingClientRect();const selected=active.getBoundingClientRect();const pinned=document.querySelector('.pinned-tabs').getBoundingClientRect();return {noScroll:list.scrollWidth<=list.clientWidth+1,activeVisible:selected.left>=bounds.left-1&&selected.right<=bounds.right+1,pinnedVisible:pinned.left>=0&&pinned.right<=innerWidth,menuVisible:document.querySelector('[data-action="tabs-menu"]').getBoundingClientRect().right<=innerWidth}})()`)
  assert(overflow.noScroll); assert(overflow.activeVisible); assert(overflow.pinnedVisible); assert(overflow.menuVisible)
  record('多标签自动缩窄，无横向滚动；固定首页和活动标签可见，全部标签菜单可访问收纳项')
  const firstTab = [...controller.tabs.keys()][0]
  const lastIndex = controller.tabs.size - 1
  await window.webContents.executeJavaScript(`window.browserShell.reorder({id:${JSON.stringify(firstTab)},index:${lastIndex}})`)
  assert.equal([...controller.tabs.keys()].at(-1), firstTab)
  assert.equal(home.webContents.getURL(), homeUrl)
  assert.throws(() => controller.reorder({ id: null, index: 0 }))
  record('标签排序接口同步更新真实标签顺序，固定首页不能被移动')
  const neighbors = [...controller.tabs.keys()]; const middle = Math.floor(neighbors.length / 2)
  controller.select(neighbors[middle]); await controller.close(neighbors[middle])
  assert.equal(controller.activeId, neighbors[middle + 1])
  record('裸域名和本机地址自动补全协议，关闭当前标签选择右邻标签，支持连续关闭')
  if (process.env.FP_SHELL_NETWORK_TEST === '1') {
    const external = await controller.openOrdinary()
    await controller.navigate({ id: external.tabId, action: 'load', url: 'www.baidu.com' })
    const page = controller.getTab(external.tabId).view.webContents
    assert(/^https?:\/\//.test(page.getURL()))
    assert((await page.executeJavaScript('document.title')).length > 0)
    record('真实外网浏览验证：裸域名 www.baidu.com 在普通标签完成加载并取得页面标题')
  }
  fs.writeFileSync(reportPath, JSON.stringify({ ok: true, runtime: process.versions.electron, chromium: process.versions.chrome, results }, null, 2))
}).catch(error => { fs.writeFileSync(reportPath, JSON.stringify({ ok: false, message: error.message, stack: error.stack, results }, null, 2)); process.exitCode = 1 }).finally(async () => {
  clearTimeout(timer)
  await controller?.shutdown().catch(() => {})
  if (window && !window.isDestroyed()) window.destroy()
  await automation?.stop()
  for (const server of servers) await new Promise(resolve => server.close(resolve))
  app.exit(process.exitCode || 0)
})
