// 独立 HTTPS/真实 Electron 会话恢复验收；凭据仅为隔离测试值，不输出报告。
const { app, BrowserWindow, session } = require('electron/main')
const fs = require('node:fs')
const https = require('node:https')
const os = require('node:os')
const path = require('node:path')
const assert = require('node:assert/strict')
const { validateSessionSnapshot, restoreSessionSnapshot } = require('../session-restore')
const { createLaunchRequest } = require('../fingerprint-envelope')
const { sealLaunch } = require('./protocol-provider')
const report = process.argv[2]; const directory = fs.mkdtempSync(path.join(os.tmpdir(), 'session-import-'))
app.setPath('userData', path.join(directory, 'app'))
let server; let window; const checks = []; let receivedCookie = false
const timeout = setTimeout(() => { fs.writeFileSync(report, JSON.stringify({ ok: false, message: '会话恢复验收超时。', checks })); app.exit(2) }, 30000)
app.whenReady().then(async () => {
  server = https.createServer({ key: fs.readFileSync(process.argv[3]), cert: fs.readFileSync(process.argv[4]) }, (req, res) => {
    if (req.headers.cookie?.includes('isolated-import-cookie=isolated-import-value')) receivedCookie = true
    res.setHeader('Content-Type', 'text/html; charset=utf-8')
    res.end('<!doctype html><html lang="zh-CN"><title>隔离恢复验收</title><script>window.firstStorage=localStorage.getItem("isolated-import-key")</script><body>会话恢复隔离验收</body></html>')
  })
  await new Promise(resolve => server.listen(0, '127.0.0.1', resolve))
  const origin = `https://127.0.0.1:${server.address().port}`
  const targetSession = session.fromPath(path.join(directory, 'session'))
  targetSession.setCertificateVerifyProc((_request, callback) => callback(0))
  const snapshot = { format: 'desktop-session-v1', origins: [origin], cookies: [{ domain: '127.0.0.1', name: 'isolated-import-cookie', value: 'isolated-import-value', path: '/', httpOnly: true, secure: true, hostOnly: true, sameSite: 'lax', expirationDate: Math.floor(Date.now() / 1000) + 3600 }], storage: { [origin]: { 'isolated-import-key': 'isolated-storage-value' } }, version: 1 }
  const encryption = createLaunchRequest('isolated-workspace', 'isolated-resource')
  const profile = { id: 'isolated-resource', fingerprint: {}, session: snapshot }
  const envelope = sealLaunch(profile, encryption.request, { scope: 'isolated-workspace', resourceId: 'isolated-resource' })
  assert(!JSON.stringify(envelope).includes('isolated-storage-value'))
  const decrypted = encryption.open(envelope)
  assert.throws(() => encryption.open(envelope), /已使用/)
  checks.push('服务端密文承载会话、加密字段不可见且单次消费')
  window = new BrowserWindow({ show: false, webPreferences: { session: targetSession, sandbox: true, nodeIntegration: false } })
  const restore = await restoreSessionSnapshot(window.webContents, validateSessionSnapshot(decrypted.session), { dataDir: path.join(directory, 'session') })
  await window.loadURL(origin)
  await restore.verify()
  assert.equal(await window.webContents.executeJavaScript('window.firstStorage'), 'isolated-storage-value')
  assert(receivedCookie)
  const restored = (await targetSession.cookies.get({})).find(cookie => cookie.name === 'isolated-import-cookie')
  assert(restored.httpOnly && restored.secure && restored.hostOnly && restored.sameSite === 'lax')
  assert.equal(await window.webContents.executeJavaScript('document.cookie.includes("isolated-import-cookie")'), false)
  checks.push('首次页面脚本前恢复localStorage，首次HTTPS请求带HttpOnly Cookie且网页不可读取')
  await window.webContents.executeJavaScript('localStorage.setItem("isolated-import-key","website-refreshed-value")')
  await window.webContents.reload(); await new Promise(resolve => window.webContents.once('did-finish-load', resolve))
  assert.equal(await window.webContents.executeJavaScript('window.firstStorage'), 'website-refreshed-value')
  assert.equal(window.webContents.debugger.isAttached(), false)
  checks.push('恢复只执行一次，导航不覆盖网站新令牌，CDP脚本与自有连接已释放')
  await restore.cleanup(); targetSession.flushStorageData()
  const previousWindow = window
  window = new BrowserWindow({ show: false, webPreferences: { session: targetSession, sandbox: true } }); previousWindow.destroy()
  const sameVersion = await restoreSessionSnapshot(window.webContents, validateSessionSnapshot(snapshot), { dataDir: path.join(directory, 'session') })
  assert.equal(sameVersion.reused, true)
  await window.loadURL(origin)
  assert.equal(await window.webContents.executeJavaScript('window.firstStorage'), 'website-refreshed-value')
  checks.push('关闭并重开目标窗口时同云版本不重注入，保留网站刷新后的存储')
  const higher = await restoreSessionSnapshot(window.webContents, validateSessionSnapshot({ ...snapshot, version: 2 }), { dataDir: path.join(directory, 'session') })
  await window.loadURL(origin + '/new-version'); await higher.verify()
  assert.equal(await window.webContents.executeJavaScript('window.firstStorage'), 'isolated-storage-value')
  await assert.rejects(restoreSessionSnapshot(window.webContents, validateSessionSnapshot(snapshot), { dataDir: path.join(directory, 'session') }), /版本较旧/)
  checks.push('更高版本允许重新恢复，旧版本不能覆盖较新会话')
  const failedDirectory = path.join(directory, 'failed-session'); fs.mkdirSync(failedDirectory)
  const failure = { ...snapshot, version: 3, cookies: [{ ...snapshot.cookies[0], name: '__Secure-isolated-test', secure: false }] }
  await assert.rejects(restoreSessionSnapshot(window.webContents, validateSessionSnapshot(failure), { dataDir: failedDirectory }), /Cookie 未能完整恢复/)
  assert.equal(fs.existsSync(path.join(failedDirectory, 'session-restore-version.json')), false)
  checks.push('恢复失败不写成功版本标记')
  fs.writeFileSync(report, JSON.stringify({ ok: true, electron: process.versions.electron, checks }, null, 2))
}).catch(error => { fs.writeFileSync(report, JSON.stringify({ ok: false, message: error.message, checks }, null, 2)); process.exitCode = 1 }).finally(() => { clearTimeout(timeout); window?.destroy(); server?.close(); app.exit(process.exitCode || 0) })
