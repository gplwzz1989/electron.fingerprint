// 本机隔离验收：真实 SaaS/MySQL/Electron，仅创建独立测试库和测试用户，不使用正式账号。
const { app, BrowserWindow, session } = require('electron/main')
const fs = require('node:fs')
const os = require('node:os')
const path = require('node:path')
const crypto = require('node:crypto')
const assert = require('node:assert/strict')
const { WorkspaceServer } = require('../saas-server/src/workspace-server')
const { getDefaultProfile } = require('../saas-server/src/fingerprint/profile-store')
const report = process.argv[2]; const directory = fs.mkdtempSync(path.join(os.tmpdir(), 'media-ui-')); let server
const results = []; const errors = []
const timer = setTimeout(() => { fs.writeFileSync(report, JSON.stringify({ ok: false, results, message: '界面验收超时。', errors })); app.exit(2) }, 45000)
async function until (operation) { for (let i = 0; i < 100; i++) { const value = await operation(); if (value) return value; await new Promise(resolve => setTimeout(resolve, 100)) }; throw new Error('界面未就绪。') }
app.whenReady().then(async () => {
  const platformService = require(process.env.MEDIA_PLATFORM_ENTRY)
  server = new WorkspaceServer({ port: 0, dataDir: directory, databaseName: 'qijie_workspace_test_' + crypto.randomBytes(10).toString('hex'), platformService })
  const address = await server.start(); const origin = `http://127.0.0.1:${address.port}`
  const db = server.database; const userId = crypto.randomUUID(); const workspaceId = crypto.randomUUID(); const environmentId = crypto.randomUUID()
  await db.execute('INSERT INTO users VALUES(?,?,?,?,?,?)', [userId, userId + '@example.com', '界面隔离验收', crypto.randomBytes(32).toString('hex'), Date.now(), Date.now()])
  await db.execute('INSERT INTO workspaces VALUES(?,?,?)', [workspaceId, '界面隔离验收', userId])
  await db.execute('INSERT INTO members VALUES(?,?,?,?,?)', [crypto.randomUUID(), workspaceId, userId, 'owner', JSON.stringify({ mode: 'all', ids: [] })])
  await db.put('environments', workspaceId, environmentId, { name: '界面验收环境', fingerprint: db.encodeFingerprint(getDefaultProfile()), fingerprintVersion: 1, startUrl: 'https://example.com' }, null)
  const auth = await db.createSession(userId)
  process.env.FP_BROWSER_DATA_DIR = path.join(directory, 'browser'); process.env.FP_APP_URL = origin + '/'; process.env.FP_AUTOMATION_PORT = '0'
  await session.defaultSession.cookies.set({ url: origin, name: 'qijie_session', value: auth.token, httpOnly: true })
  require(process.env.MEDIA_BASE_ENTRY || '../fingerprint-browser/main')
  const home = await until(() => BrowserWindow.getAllWindows().flatMap(item => item.contentView.children).map(item => item.webContents).find(item => item?.getURL() === origin + '/'))
  home.on('console-message', (_event, level, message) => { if (level >= 3) errors.push(message) })
  await until(async () => { try { return await home.executeJavaScript('Boolean(window.WorkspaceUI && window.getMediaWorkspace?.().workspaceId)') } catch { return false } })
  assert.equal(await home.executeJavaScript('typeof workspaceBridge.observeSession'), 'function')
  results.push('真实预加载桥接包含会话观察方法')
  for (const key of ['shipinhao', 'kuaishou', 'xiaohongshu', 'douyin']) {
    await home.executeJavaScript("location.hash='accounts'")
    await until(() => home.executeJavaScript("Boolean(document.querySelector('#page [data-route=\"account-platforms\"]'))"))
    await home.executeJavaScript("document.querySelector('#page [data-route=\"account-platforms\"]').click()")
    const count = await home.executeJavaScript('document.querySelectorAll("[data-platform-key]:not(:disabled)").length')
    assert.equal(count, 4)
    await home.executeJavaScript(`document.querySelector('[data-platform-key="${key}"]').click()`)
    await until(() => home.executeJavaScript("Boolean(document.querySelector('#field-account-authorize-0-1 option[value=\"" + environmentId + "\"]'))"))
    assert.equal(await home.executeJavaScript('location.hash'), '#account-authorize')
    assert.equal(await home.executeJavaScript('document.querySelectorAll("[data-media-operation]").length'), 3)
    results.push(key + '：平台选择、授权页、环境列表和操作按钮可用')
  }
  await home.executeJavaScript("document.querySelector('[data-media-operation=\"start\"]').click()")
  await until(() => home.executeJavaScript("document.getElementById('media-auth-status')?.classList.contains('status-error')"))
  assert.equal(await home.executeJavaScript("getComputedStyle(document.getElementById('media-auth-status')).color"), 'rgb(197, 57, 76)')
  assert.equal(await home.executeJavaScript("document.querySelectorAll('#navigation .nav-link span').length"), 8)
  results.push('缺少环境时显示中文红色错误，八个导航保持完整')
  const manifest = await fetch(origin + '/api/platform-runtime').then(response => response.json())
  const script = await fetch(origin + manifest.url).then(response => response.text())
  assert.equal(crypto.createHash('sha256').update(script).digest('hex'), manifest.sha256)
  assert(!errors.some(message => /SyntaxError|TypeError|ReferenceError/.test(message)))
  results.push('动态脚本完整性摘要与真实响应一致，无脚本作用域错误')
  fs.writeFileSync(report, JSON.stringify({ ok: true, results, errors }, null, 2))
}).catch(error => { fs.writeFileSync(report, JSON.stringify({ ok: false, message: error.message, stack: error.stack, results, errors }, null, 2)); process.exitCode = 1 }).finally(async () => { clearTimeout(timer); if (server) await server.stop(); app.exit(process.exitCode || 0) })
