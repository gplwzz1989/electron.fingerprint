const wait = delay => new Promise(resolve => setTimeout(resolve, delay))
async function until (operation, label) {
  for (let i = 0; i < 100; i++) { const value = await operation(); if (value) return value; await wait(50) }
  throw new Error(label || '界面状态未就绪。')
}
async function page (source) { return await window.webContents.executeJavaScript(source) }
async function route (id) {
  await page(`history.replaceState(null, '', '#${id}'); WorkspaceUI.render()`)
  await until(() => page(`WorkspaceUI.getBaseRoute() === '${id}' && !document.querySelector('#modal-root [role="dialog"]')`), '主页面未恢复：' + id)
}
async function open (id, base) {
  await page(`WorkspaceUI.openPage('${id}', ${id === 'account-authorize' ? '{platform:"shipinhao"}' : '{}'})`)
  await until(() => page(`WorkspaceUI.getRoute() === '${id}' && Boolean(WorkspaceUI.getSurface()?.closest('[role="dialog"]') || WorkspaceUI.getSurface()?.matches('[role="dialog"]'))`), '二级页面未在模态内打开：' + id)
  assert.equal(await page('WorkspaceUI.getBaseRoute()'), base, id + ' 不得替换来源页面')
  assert.equal(await page('Boolean(document.querySelector("#page h1"))'), true, '底层主页面必须仍在')
}
async function close (base) {
  await page('WorkspaceUI.closePage()')
  await until(() => page(`WorkspaceUI.getRoute() === '${base}' && !document.querySelector('#modal-root [role="dialog"]')`), '关闭后未返回来源：' + base)
}
async function input (selector, value) {
  await page(`(() => { const field=WorkspaceUI.getSurface().querySelector(${JSON.stringify(selector)}); if(!field) throw new Error('测试字段不存在：'+${JSON.stringify(selector)}); field.value=${JSON.stringify(value)}; field.dispatchEvent(new Event('input',{bubbles:true})); field.dispatchEvent(new Event('change',{bubbles:true})); })()`)
}

